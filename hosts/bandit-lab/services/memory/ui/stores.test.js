const test = require('node:test');
const assert = require('node:assert');
const {storeLinks, wikiLinks, switcherHtml} = require('./stores.js');

test('a cross-store link opens that store\'s note', () => {
  assert.equal(storeLinks('see [[firma:projects/aiia]]'),
    'see <a href="https://memory-firma.tail7facc9.ts.net/notes/projects/aiia.md">firma:projects/aiia</a>');
  assert.match(storeLinks('[[vino:a/b.md]]'), /href="https:\/\/memory\.tail7facc9\.ts\.net\/notes\/a\/b\.md"/);
});

test('plain wiki links and unknown stores are left alone', () => {
  assert.equal(storeLinks('[[projects/aiia]] [[other:x]]'), '[[projects/aiia]] [[other:x]]');
});

test('the switcher marks the current store', () => {
  const h = switcherHtml('memory-albert.tail7facc9.ts.net');
  assert.equal((h.match(/<a /g) || []).length, 3);
  assert.match(h, /aria-current="page">albert/);
  assert.ok(!switcherHtml('example.org').includes('aria-current'));
});

test('a store link nested in a wiki link cannot smuggle attributes', () => {
  const out = wikiLinks(storeLinks('[[x [[firma:a onmouseover=alert(1) b]] y]]'));
  assert.ok(!out.includes('<button'));
  assert.equal(wikiLinks('[[projects/aiia]]'), '<button class="link" data-open="projects/aiia">projects/aiia</button>');
});

const {isHuman, isLate, nextSteps, parseLagebild} = require('./stores.js');

test('human, claude and late steps follow index.sh', () => {
  assert.ok(isHuman('vino, Albert') && isHuman('owner'));
  assert.ok(!isHuman('') && !isHuman('Claude Code') && !isHuman('claude'));
  assert.ok(isLate('2026-11-12', 'open', '2026-11-13') && !isLate('2026-11-13', 'open', '2026-11-13'));
  assert.ok(!isLate('2026-11-12', 'done', '2026-11-13') && !isLate('', 'open', '2026-11-13'));
  const t = [{state: 'open', who: 'owner', n: 1}, {state: 'open', who: '', n: 2}, {state: 'doing', who: 'Albert', n: 3}, {state: 'done', who: 'x', n: 4}];
  const s = nextSteps(t);
  assert.equal(s.human.n, 3); // [/] before [ ]
  assert.equal(s.claude.n, 2);
  assert.deepEqual(nextSteps([{state: 'done', who: 'x'}]), {human: undefined, claude: undefined});
});

const LAGE = `---
title: Lagebild
type: index
permalink: main/lagebild
---
> Generated by memory-index.

## Waiting for a human
1. aiia (firma): Answer the questions (vino, Albert) LATE 2026-11-12
2. sorter (vino): Run the deploy (owner)

## Projects
| project | store | status | open | doing | late | human next | claude next | repo | changed |
|---|---|---|---|---|---|---|---|---|---|
| aiia | firma | active | 5 | 1 | 1 | Answer the questions | Draft reply | ~/src/aiia main | 2026-11-13 |
| sorter | vino | paused | 9 | 0 | 0 | Run the deploy | - | - | 2026-11-10 |
| evil | elsewhere | active | 1 | 0 | 0 | <img onerror=x> | - | - | 2026-11-10 |
`;

test('the lagebild table parses into rows, unknown stores dropped', () => {
  const rows = parseLagebild(LAGE);
  assert.equal(rows.length, 2);
  assert.deepEqual(rows[0], {project: 'aiia', store: 'firma', status: 'active', open: 5, doing: 1, late: 1, human: 'Answer the questions',
    claude: 'Draft reply', repo: '~/src/aiia main', changed: '2026-11-13', humanLate: true});
  assert.equal(rows[1].claude, '');
  assert.equal(rows[1].humanLate, false);
  assert.deepEqual(parseLagebild('no table'), []);
});
